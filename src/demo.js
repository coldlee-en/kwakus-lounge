// Original ROM: moving checkerboard controlled by the Game Boy joypad.
export function demoRom(){
 const r=new Uint8Array(32768);r.set([0,0xc3,0x50,1],0x100);r.set(new TextEncoder().encode('POCKET DEMO'),0x134);
 const code=[];const emit=(...b)=>code.push(...b);const labels={};const jumps=[];
 const label=n=>labels[n]=0x150+code.length;const jr=(op,n)=>{emit(op,0);jumps.push([code.length-1,n]);};
 emit(0xf3,0x31,0xfe,0xff,0xaf,0xe0,0x40,0x3e,0xe4,0xe0,0x47,0x21,0,0x80,0x06,8);
 label('tile');emit(0x3e,0xaa,0x22,0x3e,0x55,0x22,0x05);jr(0x20,'tile');
 emit(0x21,0,0x98,0x01,0,4);label('map');emit(0xaf,0x22,0x0b,0x78,0xb1);jr(0x20,'map');emit(0x3e,0x91,0xe0,0x40);
 label('wait');emit(0xf0,0x44,0xfe,144);jr(0x38,'wait');
 emit(0x3e,0x20,0xe0,0,0xf0,0,0xcb,0x47);jr(0x20,'left');emit(0xf0,0x43,0x3c,0xe0,0x43);
 label('left');emit(0xf0,0,0xcb,0x4f);jr(0x20,'up');emit(0xf0,0x43,0x3d,0xe0,0x43);
 label('up');emit(0xf0,0,0xcb,0x57);jr(0x20,'down');emit(0xf0,0x42,0x3d,0xe0,0x42);
 label('down');emit(0xf0,0,0xcb,0x5f);jr(0x20,'animate');emit(0xf0,0x42,0x3c,0xe0,0x42);
 label('animate');emit(0xf0,0x43,0x3c,0xe0,0x43);label('end');emit(0xf0,0x44,0xfe,144);jr(0x30,'end');emit(0xc3,labels.wait&255,labels.wait>>8);
 for(const [i,n] of jumps)code[i]=(labels[n]-(0x150+i+1))&255;r.set(code,0x150);
 let sum=0;for(let i=0x134;i<=0x14c;i++)sum=(sum-r[i]-1)&255;r[0x14d]=sum;return r.buffer;
}
